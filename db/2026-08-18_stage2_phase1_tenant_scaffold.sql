-- ── 1. The tenant root ──────────────────────────────────────────────────────
-- `status` is checked inside current_org_id() rather than only in the UI, so
-- suspending an organisation blocks it at the database (Stage 7 needs this;
-- building it in now costs one column).
--
-- `staff_names` holds what window.ARF_STAFF hardcodes today — the "who did
-- this work" picklist, which is per-practice. window.AQC_STAFF needs no home:
-- it is this list plus the firm names, which org_firms already has, so it can
-- be assembled at runtime instead of stored twice.
create table public.organizations (
  id          bigint generated by default as identity primary key,
  name        text not null,
  slug        text not null unique,
  status      text not null default 'active',
  staff_names jsonb not null default '[]'::jsonb,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint organizations_status_check
    check (status = any (array['active','suspended']))
);

-- ── 2. Membership ───────────────────────────────────────────────────────────
-- Supersedes app_users, which knows who is staff but not WHOSE staff.
--
-- email is UNIQUE GLOBALLY, not per organisation. That is the constraint that
-- enforces the project's "one person belongs to exactly one organisation"
-- decision — with a per-org unique key the same address could join two firms
-- and current_org_id() would have no single answer.
create table public.org_members (
  id         bigint generated by default as identity primary key,
  org_id     bigint not null references public.organizations(id) on delete cascade,
  email      text not null unique,
  role       text not null default 'staff',
  status     text not null default 'active',
  invited_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint org_members_role_check
    check (role = any (array['owner','admin','staff'])),
  constraint org_members_status_check
    check (status = any (array['active','inactive']))
);

-- ── 3. Letterheads ──────────────────────────────────────────────────────────
-- One row per firm the practice issues documents under. This is
-- window.REP_FIRMS + window.SERVICE_MEMO_FIRMS + window.FINAL_ACCOUNT_FIRM_KEYS
-- turned into data.
--
-- firm_key keeps the EXACT strings already stored in service_memos.firm_key,
-- bank_accounts.firm_key and party_opening_balances.firm_key. Those columns
-- are plain text with no foreign key and stay that way in this phase: adding
-- one would be a second enforcement change on top of the tenant work, and
-- those three columns are already reachable only through an org-scoped row.
--
-- is_typed marks the 'other' entry, whose name is typed per memo rather than
-- configured (service_memos.firm_other). for_final_account is
-- FINAL_ACCOUNT_FIRM_KEYS — the Balance Sheet has exactly two columns.
create table public.org_firms (
  id                bigint generated by default as identity primary key,
  org_id            bigint not null references public.organizations(id) on delete cascade,
  firm_key          text not null,
  name              text not null,
  title             text,
  address           text,
  email             text,
  phone             text,
  reg_no            text,
  m_no              text,
  pan               text,
  cop_no            text,
  signatory_name    text,
  signatory_title   text,
  logo              text,
  name_np           text,
  auditor_name_np   text,
  title_np          text,
  memo_prefix       text,
  is_typed          boolean not null default false,
  for_final_account boolean not null default false,
  is_active         boolean not null default true,
  sort_order        integer not null default 0,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  constraint org_firms_org_key_uniq unique (org_id, firm_key)
);

create index org_members_org_idx on public.org_members using btree (org_id);
create index org_firms_org_idx   on public.org_firms   using btree (org_id, sort_order);

create trigger set_organizations_updated_at before update on public.organizations
  for each row execute function public.set_updated_at();
create trigger set_org_members_updated_at   before update on public.org_members
  for each row execute function public.set_updated_at();
create trigger set_org_firms_updated_at     before update on public.org_firms
  for each row execute function public.set_updated_at();


