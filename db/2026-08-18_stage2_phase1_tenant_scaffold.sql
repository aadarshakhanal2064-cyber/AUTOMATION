-- ── 5. The one place tenancy is decided ─────────────────────────────────────
-- SECURITY DEFINER so it can read org_members regardless of that table's own
-- policies — the same pattern private.is_app_user() already uses, and what
-- keeps a policy that calls this from recursing into itself.
--
-- STABLE so Postgres evaluates it once per statement rather than once per row;
-- on a 5,639-row table that is the difference between a fast policy and a slow
-- one.
--
-- Returns NULL for a suspended organisation, an inactive member, or an unknown
-- email. Once Phase 3's policies compare against it, NULL matches no row —
-- suspension therefore blocks at the database, not in the UI.
create or replace function private.current_org_id()
returns bigint
language sql stable security definer set search_path to ''
as $function$
  select m.org_id
  from public.org_members m
  join public.organizations o on o.id = m.org_id
  where lower(m.email) = private.jwt_email()
    and m.status = 'active'
    and o.status = 'active'
  limit 1;
$function$;

revoke all on function private.current_org_id() from public;
grant execute on function private.current_org_id() to authenticated, service_role;


-- ── 6. RLS on the three new tables ──────────────────────────────────────────
-- A new table with RLS on and no policy is invisible to the app, so both go in
-- here together (CLAUDE.md §6). These are the only policies in Phase 1 that
-- are org-scoped from birth; the other 82 are rewritten in Phase 3.
alter table public.organizations enable row level security;
alter table public.org_members   enable row level security;
alter table public.org_firms     enable row level security;

create policy organizations_select_own on public.organizations
  for select to authenticated using (id = private.current_org_id());
create policy organizations_update_admin on public.organizations
  for update to authenticated
  using (id = private.current_org_id() and private.is_admin())
  with check (id = private.current_org_id());

create policy org_members_select_own on public.org_members
  for select to authenticated using (org_id = private.current_org_id());

create policy org_firms_select_own on public.org_firms
  for select to authenticated using (org_id = private.current_org_id());
create policy org_firms_insert_admin on public.org_firms
  for insert to authenticated
  with check (org_id = private.current_org_id() and private.is_admin());
create policy org_firms_update_admin on public.org_firms
  for update to authenticated
  using (org_id = private.current_org_id() and private.is_admin())
  with check (org_id = private.current_org_id());

-- org_members has deliberately NO insert/update/delete policy in this phase.
-- Adding a member is Stage 3's invitation flow; until then the only way in is
-- the Supabase dashboard, which is exactly the situation app_users is in today.

grant all on all tables    in schema public to anon, authenticated, service_role;
grant all on all sequences in schema public to anon, authenticated, service_role;


-- ── 7. org_id on all 22 tenant-owned tables ─────────────────────────────────
-- Every existing table except app_users, which org_members supersedes.
--
-- Two statements per table, deliberately not one:
--   ADD COLUMN with no default is a metadata-only change — it does not rewrite
--   the table. SET DEFAULT afterwards is also metadata-only and does NOT
--   backfill existing rows. Combining them into ADD COLUMN ... DEFAULT would
--   force a full rewrite of every table AND stamp every existing row with
--   whatever current_org_id() returns for the migration's own connection,
--   which is NULL. Phase 2 backfills explicitly instead.
--
-- The default is set NOW rather than in Phase 3 on purpose: any row the firm
-- creates between Phase 2's backfill and Phase 3's enforcement then gets its
-- owner automatically, so the backfill cannot be overtaken by ordinary use.
--
-- ON DELETE RESTRICT: deleting an organisation must not silently cascade away
-- its books. Deletion is Stage 7, and it is meant to be a deliberate,
-- rehearsed, export-first operation.
do $$
declare t text;
begin
  foreach t in array array[
    'clients', 'client_shareholders',
    'send_logs', 'audit_log',
    'service_memos', 'service_memo_fee_skips',
    'depreciation_schedules',
    'bank_accounts', 'bank_transactions',
    'party_opening_balances',
    'financial_statements', 'projection_reports',
    'document_register', 'saved_documents',
    'audit_report_finalization', 'audit_checklists',
    'work_done', 'work_todos',
    'autobooks_books', 'autobooks_entries',
    'autobooks_parties', 'autobooks_adjustments'
  ] loop
    execute format(
      'alter table public.%I add column org_id bigint
         references public.organizations(id) on delete restrict', t);
    execute format(
      'alter table public.%I alter column org_id set default private.current_org_id()', t);
    execute format(
      'create index %I on public.%I using btree (org_id)', t || '_org_idx', t);
  end loop;
end $$;


-- ── 8. Verify ───────────────────────────────────────────────────────────────
-- Expect, measured on the staging rehearsal:
--   orgs 1 · members 3 · firms 5 · fn_exists t
--   org_id_columns 24 · org_indexes 24 — twenty-two tenant tables PLUS
--     org_members.org_id and org_firms.org_id, which are those tables' own
--     foreign keys and are not part of the 22.
--   with_default 22 — this is the number that pins the tenant tables exactly,
--     since only they get private.current_org_id() as a default.
--   policies 88 — the 82 that already existed, untouched, plus 6 new.
--
-- org_id is NULL on every existing row at this point. That is correct: nothing
-- reads the column yet, and Phase 2 is what fills it.
select
  (select count(*) from public.organizations)                          as orgs,
  (select count(*) from public.org_members)                            as members,
  (select count(*) from public.org_firms)                              as firms,
  (select count(*) from information_schema.columns
     where table_schema='public' and column_name='org_id')             as org_id_columns,
  (select count(*) from information_schema.columns
     where table_schema='public' and column_name='org_id'
       and column_default is not null)                                 as with_default,
  (select count(*) from pg_indexes
     where schemaname='public' and indexname like '%\_org\_idx')       as org_indexes,
  (select count(*) from pg_policies where schemaname='public')         as policies,
  (select exists (select 1 from pg_proc p join pg_namespace n on n.oid=p.pronamespace
     where n.nspname='private' and p.proname='current_org_id'))        as current_org_id_exists;
